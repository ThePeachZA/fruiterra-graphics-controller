//! Embedded overlays and bundled assets.
//!
//! Overlay HTML and the bundled asset set are compiled into the binary with
//! [`rust_embed`]. Debug builds read from the source tree so edits are visible
//! without a rebuild; release builds embed the bytes.
//!
//! The bundled manifest is hashed at build time by `build.rs`, which emits
//! [`BUNDLED_ASSETS`]. That list is the single source of truth for bundled
//! metadata; the embedded bytes are addressed by the manifest's relative path.

use std::borrow::Cow;

use fgc_core::{Asset, AssetCategory, AssetId};
use rust_embed::RustEmbed;

/// Files under `crates/server/assets/` (bundled assets and fonts).
#[derive(RustEmbed)]
#[folder = "assets/"]
struct EmbeddedAssets;

/// Files under `crates/server/overlays/`.
#[derive(RustEmbed)]
#[folder = "overlays/"]
struct EmbeddedOverlays;

/// Metadata for one bundled asset, generated by `build.rs`.
///
/// Field order and types are part of the generated file's contract; see
/// `build.rs::render_asset`.
pub struct BundledAsset {
    /// Display name used by projection lookups.
    pub name: &'static str,
    /// Asset category.
    pub category: AssetCategory,
    /// SHA-256 of the file bytes.
    pub hash: &'static str,
    /// File extension from the allow-list.
    pub ext: &'static str,
    /// Deterministic identity, `b:<hash>`.
    pub id: &'static str,
    /// Linked icon asset identity, if any.
    pub icon: Option<&'static str>,
    /// Linked portrait asset identity, if any.
    pub portrait: Option<&'static str>,
    /// Linked game-mode asset identity, if any.
    pub game_mode: Option<&'static str>,
    /// Path relative to the embedded `assets/` folder.
    pub path: &'static str,
}

include!(concat!(env!("OUT_DIR"), "/bundled_assets.rs"));

/// Every bundled asset, sorted by name for deterministic builds.
#[must_use]
pub fn bundled_assets() -> &'static [BundledAsset] {
    BUNDLED_ASSETS
}

/// Returns the embedded bytes for a path relative to `assets/`.
#[must_use]
pub fn bundled_asset_bytes(path: &str) -> Option<Cow<'static, [u8]>> {
    EmbeddedAssets::get(path).map(|file| file.data)
}

/// Returns the embedded bytes for a bundled asset addressed by content hash.
#[must_use]
pub fn bundled_asset_bytes_by_hash(hash: &str, ext: &str) -> Option<Cow<'static, [u8]>> {
    let asset = BUNDLED_ASSETS
        .iter()
        .find(|asset| asset.hash == hash && asset.ext == ext)?;
    bundled_asset_bytes(asset.path)
}

/// Returns the embedded bytes for one overlay file.
#[must_use]
pub fn embedded_overlay(name: &str) -> Option<Cow<'static, [u8]>> {
    EmbeddedOverlays::get(name).map(|file| file.data)
}

/// Returns the embedded bytes for one bundled font.
#[must_use]
pub fn embedded_font(name: &str) -> Option<Cow<'static, [u8]>> {
    EmbeddedAssets::get(&format!("fonts/{name}")).map(|file| file.data)
}

/// Builds domain [`Asset`] records for every bundled asset.
///
/// The catalogue merges these with the user's assets. Links are resolved to
/// the deterministic `b:<hash>` identities emitted by `build.rs`.
#[must_use]
pub fn bundled_catalog() -> Vec<Asset> {
    BUNDLED_ASSETS
        .iter()
        .filter_map(|entry| {
            let mut asset =
                Asset::new_bundled(entry.name, entry.category, entry.hash, entry.ext).ok()?;
            asset.icon = entry.icon.map(AssetId::from_raw);
            asset.portrait = entry.portrait.map(AssetId::from_raw);
            asset.game_mode = entry.game_mode.map(AssetId::from_raw);
            Some(asset)
        })
        .collect()
}
