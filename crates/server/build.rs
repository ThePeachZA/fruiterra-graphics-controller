//! Hashes the bundled asset manifest at build time.
//!
//! The generated `bundled_assets.rs` is deterministic: entries are sorted and
//! contain only relative paths, hashes and metadata. The build fails when a
//! referenced file is missing or has an extension outside the asset allow-list.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;
use sha2::{Digest, Sha256};

/// Extensions accepted by the content-addressed asset store.
///
/// Kept in sync with `fgc_core::ALLOWED_EXTENSIONS`; the bundled-manifest
/// integration test rejects any embedded file outside that allow-list.
const ALLOWED_EXTENSIONS: &[&str] = &["png", "jpg", "jpeg", "webp", "gif", "svg"];

#[derive(Debug, Deserialize)]
struct Manifest {
    #[allow(dead_code)]
    #[serde(default)]
    version: u32,
    assets: Vec<ManifestEntry>,
}

#[derive(Debug, Deserialize)]
struct ManifestEntry {
    name: String,
    category: String,
    file: String,
    #[serde(default)]
    icon: Option<String>,
    #[serde(default)]
    portrait: Option<String>,
    #[serde(default, rename = "gameMode")]
    game_mode: Option<String>,
}

#[derive(Debug)]
struct ResolvedAsset {
    name: String,
    category: String,
    hash: String,
    ext: String,
    id: String,
    icon: Option<String>,
    portrait: Option<String>,
    game_mode: Option<String>,
    embed_path: String,
}

fn main() {
    if let Err(error) = run() {
        panic!("bundled asset manifest failed: {error}");
    }
}

fn run() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let bundled_dir = manifest_dir.join("assets").join("bundled");
    let manifest_path = bundled_dir.join("manifest.json");

    println!("cargo:rerun-if-changed={}", manifest_path.display());
    println!("cargo:rerun-if-changed={}", bundled_dir.display());

    let manifest_text = fs::read_to_string(&manifest_path)?;
    let manifest: Manifest = serde_json::from_str(&manifest_text)?;

    let mut resolved = Vec::with_capacity(manifest.assets.len());
    for entry in manifest.assets {
        resolved.push(resolve_entry(&bundled_dir, entry)?);
    }

    let ids_by_name = build_name_index(&resolved)?;
    let mut emitted: Vec<String> = Vec::with_capacity(resolved.len());
    for asset in &resolved {
        let icon = resolve_link(&ids_by_name, asset.icon.as_deref(), &asset.name)?;
        let portrait = resolve_link(&ids_by_name, asset.portrait.as_deref(), &asset.name)?;
        let game_mode = resolve_link(&ids_by_name, asset.game_mode.as_deref(), &asset.name)?;
        emitted.push(render_asset(asset, icon, portrait, game_mode));
    }

    // Deterministic output: the manifest order is irrelevant to the build.
    emitted.sort();

    let generated = format!(
        "// @generated by build.rs from assets/bundled/manifest.json.\n\
         // Do not edit by hand.\n\
         pub static BUNDLED_ASSETS: &[BundledAsset] = &[\n{}\n];\n",
        emitted.join("\n")
    );

    let out_dir = PathBuf::from(env::var("OUT_DIR")?);
    fs::write(out_dir.join("bundled_assets.rs"), generated)?;
    Ok(())
}

fn resolve_entry(
    bundled_dir: &Path,
    entry: ManifestEntry,
) -> Result<ResolvedAsset, Box<dyn std::error::Error>> {
    let category = category_variant(&entry.category).ok_or_else(|| {
        format!(
            "asset `{}` has unknown category `{}`",
            entry.name, entry.category
        )
    })?;

    let relative = Path::new(&entry.file);
    if relative.is_absolute()
        || relative
            .components()
            .any(|component| matches!(component, std::path::Component::ParentDir))
    {
        return Err(format!(
            "asset `{}` has an unsafe file path `{}`",
            entry.name, entry.file
        )
        .into());
    }

    let absolute = bundled_dir.join(relative);
    let bytes = fs::read(&absolute).map_err(|source| {
        format!(
            "asset `{}` is missing at `{}`: {source}",
            entry.name,
            absolute.display()
        )
    })?;

    let ext = absolute
        .extension()
        .and_then(|value| value.to_str())
        .map(str::to_ascii_lowercase)
        .ok_or_else(|| format!("asset `{}` has no file extension", entry.name))?;
    if !ALLOWED_EXTENSIONS.contains(&ext.as_str()) {
        return Err(format!("asset `{}` uses unsupported extension `{ext}`", entry.name).into());
    }

    let hash = hash_bytes(&bytes);
    let id = format!("b:{hash}");
    let embed_path = format!("bundled/{}", entry.file.replace('\\', "/"));

    Ok(ResolvedAsset {
        name: entry.name,
        category: category.to_owned(),
        hash,
        ext,
        id,
        icon: entry.icon,
        portrait: entry.portrait,
        game_mode: entry.game_mode,
        embed_path,
    })
}

fn build_name_index(
    assets: &[ResolvedAsset],
) -> Result<BTreeMap<String, String>, Box<dyn std::error::Error>> {
    let mut index = BTreeMap::new();
    for asset in assets {
        if index.insert(asset.name.clone(), asset.id.clone()).is_some() {
            return Err(format!("duplicate bundled asset name `{}`", asset.name).into());
        }
    }
    Ok(index)
}

fn resolve_link(
    index: &BTreeMap<String, String>,
    link: Option<&str>,
    owner: &str,
) -> Result<Option<String>, Box<dyn std::error::Error>> {
    let Some(link) = link else {
        return Ok(None);
    };
    index
        .get(link)
        .map(|id| Some(id.clone()))
        .ok_or_else(|| format!("asset `{owner}` links to unknown asset `{link}`").into())
}

fn render_asset(
    asset: &ResolvedAsset,
    icon: Option<String>,
    portrait: Option<String>,
    game_mode: Option<String>,
) -> String {
    format!(
        "    BundledAsset {{\n\
         \x20       name: {name},\n\
         \x20       category: {category},\n\
         \x20       hash: {hash},\n\
         \x20       ext: {ext},\n\
         \x20       id: {id},\n\
         \x20       icon: {icon},\n\
         \x20       portrait: {portrait},\n\
         \x20       game_mode: {game_mode},\n\
         \x20       path: {path},\n\
         \x20   }},",
        name = rust_string(&asset.name),
        category = asset.category,
        hash = rust_string(&asset.hash),
        ext = rust_string(&asset.ext),
        id = rust_string(&asset.id),
        icon = rust_option(icon),
        portrait = rust_option(portrait),
        game_mode = rust_option(game_mode),
        path = rust_string(&asset.embed_path),
    )
}

fn rust_string(value: &str) -> String {
    format!("{value:?}")
}

fn rust_option(value: Option<String>) -> String {
    match value {
        Some(value) => format!("Some({})", rust_string(&value)),
        None => "None".to_owned(),
    }
}

fn hash_bytes(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    format!("{:x}", hasher.finalize())
}

fn category_variant(category: &str) -> Option<&'static str> {
    Some(match category {
        "logo" => "AssetCategory::Logo",
        "portrait" => "AssetCategory::Portrait",
        "map" => "AssetCategory::Map",
        "hero" => "AssetCategory::Hero",
        "game-mode" => "AssetCategory::GameMode",
        "role" => "AssetCategory::Role",
        "side" => "AssetCategory::Side",
        _ => return None,
    })
}
